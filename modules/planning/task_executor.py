def main():
    """Command-line interface for task executor."""
    import argparse

    parser = argparse.ArgumentParser(description="Task Executor")
    parser.add_argument("--vault", type=str, help="Vault path")
    parser.add_argument("--execute", type=str, help="Execute plan from file")
    parser.add_argument("--status", type=str, help="Get execution status")
    parser.add_argument("--recent", action="store_true", help="Show recent executions")

    args = parser.parse_args()

    print("=" * 70)
    print("Task Executor")
    print("=" * 70)

    try:
        vault_path = Path(args.vault) if args.vault else Path.cwd() / "Vault"
        executor = TaskExecutor(vault_path)

        if args.execute:
            plan_file = Path(args.execute)
            if plan_file.exists():
                plan = json.loads(plan_file.read_text())
                print(f"\n⚡ Executing plan from {plan_file.name}...")
                result = executor.execute_plan(plan)
                print(f"\n{'='*70}")
                print(f"Execution: {result.execution_id}")
                print(f"Status: {result.status}")
                print(f"Steps: {result.completed_steps}/{result.total_steps} completed")
                if result.error:
                    print(f"Error: {result.error}")
            else:
                print(f"Plan file not found: {plan_file}")

        elif args.status:
            status = executor.get_execution_status(args.status)
            if status:
                print(f"\n📊 Execution Status:")
                print(f"   Status: {status['status']}")
                print(f"   Completed Steps: {status['completed_steps']}/{status['total_steps']}")
            else:
                print(f"Execution not found: {args.status}")

        elif args.recent:
            executions = executor.get_recent_executions()
            print(f"\n📋 Recent Executions:")
            for exec_data in executions[:5]:
                print(f"   - {exec_data['execution_id']}: {exec_data['status']} "
                      f"({exec_data['completed_steps']}/{exec_data['total_steps']})")

        else:
            print("\nUsage: python -m modules.planning.task_executor --execute|--status|--recent")

    except Exception as e:
        print(f"\n❌ Error: {e}")


if __name__ == "__main__":
    main()
