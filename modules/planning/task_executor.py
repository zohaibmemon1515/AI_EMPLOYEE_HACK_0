def create_executor(
    vault_path: Path = None,
    max_retries: int = 3
) -> TaskExecutor:
    """
    Create a task executor.

    Args:
        vault_path: Path to vault
        max_retries: Maximum retry attempts

    Returns:
        TaskExecutor instance
    """
    return TaskExecutor(vault_path, max_retries)


